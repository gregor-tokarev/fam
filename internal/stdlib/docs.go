package stdlib

import (
	"context"
	"fmt"
	"path"
	"strings"

	"github.com/gregor-tokarev/fam/internal/engine"
	"github.com/gregor-tokarev/fam/internal/pklgen/tasks"
)

// Docs returns the standard catalogue with fixed Linux facts.
func Docs(ctx context.Context) ([]byte, error) {
	f := LinuxFacts()
	groups, err := Read(ctx, f)
	if err != nil {
		return nil, err
	}
	var out strings.Builder
	out.WriteString("# Standard bundles\n\nGenerated with `go run ./cmd/fam internal std-docs`. Do not edit this file.\n\nImport `@fam/std.pkl`, then select a bundle, for example `bundles { std.computer.agentBrowser }`.\nThe tables use fixed Linux facts: Ubuntu 26.04, amd64. Skills can differ on other platforms.\nA bundle lists secret names. The config supplies their values.\n")
	cell := func(s string) string { return strings.NewReplacer("|", "\\|", "\n", " ", "\r", "").Replace(s) }
	for _, g := range groups {
		fmt.Fprintf(&out, "\n## %s\n\n| Bundle | Description | Install | Skills | Secrets |\n|---|---|---|---|---|\n", g.Name)
		for _, entry := range g.Bundles {
			b := entry.Bundle
			var install, skills []string
			for _, t := range b.Tasks {
				switch x := t.(type) {
				case tasks.Package:
					if p := x.GetPackage(); p != nil && *p != nil {
						name, mgr, err := engine.PackageSpec(*p, "", f)
						if err != nil {
							return nil, fmt.Errorf("std.%s.%s: %w", g.Name, entry.Name, err)
						}
						install = append(install, mgr+": `"+name+"`")
					} else if cmd := x.GetInstall(); cmd != nil {
						install = append(install, "script: `"+*cmd+"`")
					}
				case tasks.GitHubRelease:
					tag := "latest"
					if x.GetTag() != nil {
						tag = *x.GetTag()
					}
					install = append(install, "GitHub release: `"+x.GetRepo()+"` ("+tag+")")
				case tasks.GitHubSkill:
					name := path.Base(x.GetPath())
					if x.GetName() != nil {
						name = *x.GetName()
					}
					skills = append(skills, name)
				case tasks.Skill:
					name := path.Base(x.GetPath())
					if name == "skill" {
						name = b.Name
					}
					if x.GetName() != nil {
						name = *x.GetName()
					}
					skills = append(skills, name)
				case tasks.Script:
					install = append(install, "script: "+x.GetName())
				}
			}
			desc := ""
			if b.Description != nil {
				desc = *b.Description
			}
			list := func(values []string) string {
				if len(values) == 0 {
					return "—"
				}
				return cell(strings.Join(values, ", "))
			}
			fmt.Fprintf(&out, "| `std.%s.%s` | %s | %s | %s | %s |\n", g.Name, entry.Name, cell(desc), list(install), list(skills), list(b.RequiredSecrets))
		}
	}
	return []byte(out.String()), nil
}
